def _m(s):
    """Match key: norm(), then collapse stretched alef and any letter typed 3+ times ("هلاا" == "هلا")."""
    return re.sub(r'(.)\1{2,}', r'\1', re.sub('ا+', 'ا', norm(s)))


_KEYS = {k: [(_m(p), p) for p in v if _m(p)] for k, v in LISTS.items()}


def hit(list_name, text, raw=''):
    """First phrase of the list found in text, or None. Short words must stand alone (optional و/ف prefix)."""
    t = ' ' + _m(text) + ' '
    for key, phrase in _KEYS[list_name]:
        if len(key) >= 4:
            if key in t:
                return phrase
        elif re.search(r'\s[وف]?' + re.escape(key) + r'\s', t):
            return phrase
    for p in LISTS[list_name]:  # punctuation-only phrases, e.g. "؟؟"
        if not _m(p) and p in raw:
            return p
    return None
